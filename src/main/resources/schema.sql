-- Script de criação das tabelas do Chat Multiusuário.
-- Testado no H2 (banco padrão do projeto). Também funciona no PostgreSQL.
-- No MySQL/MariaDB, troque a coluna id por:  id BIGINT AUTO_INCREMENT PRIMARY KEY
-- e remova as duas instruções "ALTER TABLE ... ADD COLUMN IF NOT EXISTS" (o MySQL não as aceita).
-- É executado automaticamente na subida do servidor (idempotente).

-- Mensagens de qualquer tipo.
--   tipo    = GERAL (sala comum), GRUPO ou PRIVADA
--   destino = nome do grupo (GRUPO) ou do destinatário (PRIVADA); nulo em GERAL
CREATE TABLE IF NOT EXISTS mensagem (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remetente VARCHAR(20)  NOT NULL,
    conteudo  VARCHAR(500) NOT NULL,
    horario   TIMESTAMP    NOT NULL,
    tipo      VARCHAR(10)  DEFAULT 'GERAL' NOT NULL,
    destino   VARCHAR(20)
);

-- Migração: bancos criados pela versão anterior (só com mensagens gerais) ganham as novas colunas.
ALTER TABLE mensagem ADD COLUMN IF NOT EXISTS tipo VARCHAR(10) DEFAULT 'GERAL' NOT NULL;
ALTER TABLE mensagem ADD COLUMN IF NOT EXISTS destino VARCHAR(20);

CREATE INDEX IF NOT EXISTS idx_mensagem_horario ON mensagem (horario);
CREATE INDEX IF NOT EXISTS idx_mensagem_tipo_destino ON mensagem (tipo, destino);

-- Grupos de conversa. O nome é guardado em minúsculas (chave).
CREATE TABLE IF NOT EXISTS grupo (
    nome      VARCHAR(20) PRIMARY KEY,
    criador   VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP   NOT NULL
);

-- Membros de cada grupo (nome do usuário em minúsculas).
CREATE TABLE IF NOT EXISTS grupo_membro (
    grupo   VARCHAR(20) NOT NULL,
    usuario VARCHAR(20) NOT NULL,
    PRIMARY KEY (grupo, usuario)
);
